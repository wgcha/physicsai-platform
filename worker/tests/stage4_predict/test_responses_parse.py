"""`physicsai_core.stage4_predict.responses` 단위(phase3 §14.6, V3-S9-16): 요청 줄·RESPONSES.txt 파싱·stat 적용."""

from __future__ import annotations

import pytest

from physicsai_core.stage4_predict import responses as R


def _r(name, stat="MAX", **spec):
    return {"name": name, "unit": "", "spec": {"source": "H3D", "subcase": 1, "datatype": "Stress", "component": "vonMises",
                                               "layer": "", "stat": stat, **spec}}


def test_request_line_order_and_validation():
    reqs, skipped = R.build_requests([
        _r("A", layer="Max"), _r("B", subcase=0), _r("C|x"), _r("D", stat="AVG"), {"name": "E", "spec": {}},
        {"name": "F", "spec": {"SOURCE": "H3D", "SUBCASE": 2, "DATATYPE": "Displacement", "COMPONENT": "Mag", "STAT": "absmax"}},
        {"name": "G", "spec": {"source": "XYDATA", "datatype": "x", "component": "y"}},
    ])
    assert [q.line() for q in reqs] == ["A|1|Stress|vonMises|Max", "F|2|Displacement|Mag|"]
    assert reqs[1].stat == "ABSMAX"
    assert skipped == {"B": "SPEC_INVALID", "C|x": "SPEC_INVALID", "D": "SPEC_INVALID", "E": "NOT_H3D", "G": "NOT_H3D"}
    assert R.requests_text(reqs).splitlines()[:2] == ["# H3D_REQUESTS.txt generated by PhysicsAI platform (phase3 §14.6)",
                                                      "# NAME|SUBCASE|DATATYPE|COMPONENT|LAYER"]


def test_empty_component_request_line_and_parse():
    """D3-54: component는 선택 — 빈 값·키 없음은 요청 줄의 빈 필드(layer와 같은 처리), RESPONSES.txt는 이름으로 읽는다."""
    corner = {"name": "Corner", "unit": "MPa", "spec": {"source": "H3D", "subcase": 1, "datatype": "CornerStress",
                                                         "component": "", "layer": "", "stat": "ABSMAX"}}
    nokey = {"name": "Corner2", "spec": {"SOURCE": "H3D", "SUBCASE": 1, "DATATYPE": "CornerStress", "STAT": "MAX"}}
    reqs, skipped = R.build_requests([corner, nokey])
    assert skipped == {} and [q.line() for q in reqs] == ["Corner|1|CornerStress||", "Corner2|1|CornerStress||"]
    assert R.requests_text(reqs).splitlines()[2:] == ["Corner|1|CornerStress||", "Corner2|1|CornerStress||"]
    p = R.parse_responses_text("# RESPONSES.txt generated\nRESP:Corner_MIN=-3.0e+01\nRESP:Corner_MAX=2.5e+01\n"
                               "RESP:Corner2=DATATYPE_ERR\n")
    vals, why = R.pick_values([corner, nokey], p)
    assert vals == {"Corner": 30.0, "Corner2": None} and why == {"Corner2": "DATATYPE_ERR"}


def test_field_order_is_one_constant(monkeypatch):
    """E4-9-5에서 순서가 다르면 REQUEST_FIELDS 상수 하나만 바꾼다."""
    monkeypatch.setattr(R, "REQUEST_FIELDS", ("NAME", "DATATYPE", "COMPONENT", "LAYER", "SUBCASE"))
    req, _ = R.h3d_request(_r("A"))
    assert req.line() == "A|Stress|vonMises||1"
    assert R.requests_text([req]).splitlines()[1] == "# NAME|DATATYPE|COMPONENT|LAYER|SUBCASE"


def test_parse_and_stats():
    text = ("﻿# RESPONSES.txt generated 2026-10-16\n"
            "RESP:Max_S_MIN=  -1.2500000000e+01\nRESP:Max_S_MAX=   3.0000000000e+02\n"
            "RESP:Lo_MIN=-5.0e+00\nRESP:Lo_MAX=2.0e+00\n"
            "RESP:Bad=NO_VALUE\nRESP:Open=OPEN_ERROR\nRESP:Nan_MAX=nan\njunk line\n")
    p = R.parse_responses_text(text)
    assert p.values == {"Max_S_MIN": -12.5, "Max_S_MAX": 300.0, "Lo_MIN": -5.0, "Lo_MAX": 2.0}
    assert p.failures == {"Bad": "NO_VALUE", "Open": "OPEN_ERROR", "Nan_MAX": "NO_VALUE"}
    resps = [_r("Max_S"), _r("Lo", "MIN"), _r("Lo2", "ABSMAX"), _r("Bad"), _r("Open", "ABSMAX"), _r("Nan"), _r("Gone"),
             {"name": "Legacy", "spec": {"type": "max"}}]
    resps[2]["name"] = "Lo"  # 같은 이름 두 stat은 정의 검증(API)이 막지만 파서는 stat대로 계산
    vals, why = R.pick_values(resps, p)
    assert vals["Max_S"] == 300.0 and vals["Lo"] == 5.0                     # ABSMAX = max(|-5|, |2|) (뒤 정의가 덮음)
    assert why == {"Bad": "NO_VALUE", "Open": "OPEN_ERROR", "Nan": "NO_VALUE", "Gone": "MISSING", "Legacy": "NOT_H3D"}
    vals, why = R.pick_values([_r("A"), {"name": "B"}], None)
    assert vals == {"A": None, "B": None} and why == {"A": "EXTRACT_FAILED", "B": "NOT_DEFINED"}
    assert R.name_value_csv_text({"A": 1.5, "B": None}) == "name,value\nA,1.5\nB,\n"


@pytest.mark.parametrize("names,expect", [(["a_pred.h3d", "b.h3d"], ["a_pred.h3d"]), (["b.h3d", "c.H3D"], ["b.h3d", "c.H3D"])])
def test_h3d_candidates(tmp_path, names, expect):
    for n in names:
        (tmp_path / n).write_bytes(b"x")
    assert R.h3d_candidates(str(tmp_path)) == expect
