import pytest
from physicsai_test_support import read_record

TCL_NAME = "H3D_StaticMinMax_to_CSV_FAST.tcl"
NEW_CMD = ["{hw}", "-clientconfig", "hwpost.dat", "-b", "-tcl", "{extract_tcl}"]
VALUES = {"values": {"THK_1": 3.0, "N_RIB": 4}, "value_source": "manual"}


def _spec(dt: str, comp: str, stat: str, subcase: int = 1, layer: str = "") -> dict[str, Any]:
    return {"source": "H3D", "subcase": subcase, "datatype": dt, "component": comp, "layer": layer, "stat": stat}


RESPS = [
    {"name": "MaxStress", "unit": "MPa", "spec": _spec("Stress", "vonMises", "MAX", layer="Max")},
    {"name": "MinDisp", "unit": "mm", "spec": _spec("Displacement", "X", "MIN")},
    {"name": "AbsX", "unit": "mm", "spec": _spec("Displacement", "Mag", "ABSMAX", subcase=2)},
    {"name": "NoVal", "unit": "", "spec": _spec("Stress", "vonMises", "MAX")},
    {"name": "Legacy", "unit": "", "spec": {"type": "max"}},          # 추출 정의(H3D) 없음 → null
]
GOLDEN = ("# H3D_REQUESTS.txt generated by PhysicsAI platform (phase3 §14.6)\n"
          "# NAME|SUBCASE|DATATYPE|COMPONENT|LAYER\n"
          "MaxStress|1|Stress|vonMises|Max\n"
          "MinDisp|1|Displacement|X|\n"
          "AbsX|2|Displacement|Mag|\n"
          "NoVal|1|Stress|vonMises|\n")


@pytest.fixture()
def tcl(tmp_path) -> Path:
    p = tmp_path / "resources" / "BATCHRUN" / TCL_NAME
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text("# fake extract tcl (tbcload)\n")
    return p


def _env(predict_env, tcl, **kw):
    return predict_env(commands={"response_extract": NEW_CMD}, resources={"extract_minmax_tcl": str(tcl)}, **kw)


def test_v3_s9_16_requests_golden_argv_and_values(predict_env, tcl, fake_record, monkeypatch):
    monkeypatch.setenv("FAKE_HW_NO_VALUE", "NoVal")
    env = _env(predict_env, tcl)
    ps = env.param_set()
    env.set_responses(ps["id"], RESPS)
    j = env.submit("PREDICT", VALUES)
    assert env.w.run_once_slot() == "SUCCEEDED", env.job(j["id"])
    jd = env.job(j["id"])
    R = env.predict_dir(j["id"]) / "RESULT"
    assert (R / "H3D_REQUESTS.txt").read_text(encoding="utf-8") == GOLDEN
    assert (R / TCL_NAME).read_text() == tcl.read_text()                       # 원본 TCL을 작업 폴더로 복사
    assert "RESP:MaxStress_MAX=" in (R / "RESPONSES.txt").read_text()
    hw = [r for r in read_record(fake_record) if r["tool"] == "hw" and r["argv"][-2:-1] == ["-tcl"]][-1]
    assert hw["argv"][1:] == ["-clientconfig", "hwpost.dat", "-b", "-tcl", (R / TCL_NAME).as_posix()]
    assert hw["cwd"] == str(R)
    table = {r["name"]: r["predicted"] for r in jd["result"]["response_table"]}
    assert table == {"MaxStress": 100.0, "MinDisp": -2.5, "AbsX": 120.0, "NoVal": None, "Legacy": None}
    assert jd["result"]["response_errors"] == {"NoVal": "NO_VALUE", "Legacy": "NOT_H3D"}
    rows = list(csv.reader((env.predict_dir(j["id"]) / "responses_pred.csv").open()))
    assert rows[0] == ["name", "value"] and rows[1] == ["MaxStress", "100.0"] and rows[4] == ["NoVal", ""]
    warn = [w for w in jd["warnings"] if w["code"] == "RESPONSE_NO_VALUE"]
    assert len(warn) == 1 and "NoVal" in warn[0]["message"] and "Legacy" in warn[0]["message"]
    steps = env.steps(j["id"])
    assert steps["RESPONSE_EXTRACT"]["state"] == steps["RESPONSE_TABLE"]["state"] == "SUCCEEDED"
    log = (env.sroot / "logs" / j["id"] / "job.log").read_text()
    assert "RESPONSES.log" in log and "Request 'MaxStress'" in log            # RESPONSES.log를 step 로그에 덧붙임


@pytest.mark.parametrize("mode", ["tool_fail", "tcl_missing", "two_h3d"])
def test_v3_s9_16_extract_failure_keeps_prediction(predict_env, tcl, monkeypatch, mode):
    env = _env(predict_env, tcl)
    ps = env.param_set()
    env.set_responses(ps["id"], RESPS[:2])
    if mode == "tool_fail":
        monkeypatch.setenv("FAKE_TOOL_MODE_HWRESP", "fail")
    elif mode == "tcl_missing":
        tcl.unlink()
    j = env.submit("PREDICT", VALUES)
    if mode == "two_h3d":                                                      # 예측 전에 RESULT에 다른 h3d를 둔다
        R = env.predict_dir(j["id"]) / "RESULT"
        R.mkdir(parents=True, exist_ok=True)
        (R / "other.h3d").write_bytes(b"x")
    assert env.w.run_once_slot() == "SUCCEEDED", env.job(j["id"])
    jd = env.job(j["id"])
    assert [r["predicted"] for r in jd["result"]["response_table"]] == [None, None]
    code = "RESP_H3D_AMBIGUOUS" if mode == "two_h3d" else "RESPONSE_EXTRACT_FAILED"
    assert code in [w["code"] for w in jd["warnings"]]
    assert jd["result"]["response_errors"] == {"MaxStress": "EXTRACT_FAILED", "MinDisp": "EXTRACT_FAILED"}
    assert env.steps(j["id"])["RESPONSE_EXTRACT"]["state"] == "SUCCEEDED"


def test_v3_s9_16_nonzero_with_output_and_no_definitions(predict_env, tcl, fake_record, monkeypatch):
    env = _env(predict_env, tcl)
    ps = env.param_set()
    env.set_responses(ps["id"], RESPS[:1])
    monkeypatch.setenv("FAKE_TOOL_MODE_HWRESP", "nonzero_with_output")
    j = env.submit("PREDICT", VALUES)
    assert env.w.run_once_slot() == "SUCCEEDED"
    jd = env.job(j["id"])
    assert jd["result"]["response_table"][0]["predicted"] == 100.0
    assert "EXIT_NONZERO_IGNORED" in [w["code"] for w in jd["warnings"]]
    # 응답 정의 없음 → RESPONSE_EXTRACT SKIPPED, 도구 미실행
