def settings_text(*, h3d_path: str, out_dir: str, display: Mapping[str, Any], max_frames: int, include_disp: bool) -> str:
    """extract_settings.tcl(ASCII, `/` 경로 — capture_settings.tcl과 같은 이스케이프 규칙)."""
    rows = [
        ("H3D_PATH", tcl_quote(h3d_path.replace("\\", "/"))),
        ("OUTDIR", tcl_quote(out_dir.replace("\\", "/"))),
        ("FIELD", tcl_quote(str(display.get("field") or ""))),
        ("DCOMP", tcl_quote(str(display.get("component") or display.get("comp") or ""))),
        ("AVGMODE", tcl_quote(str(display.get("avgmode") or ""))),
        ("MAX_FRAMES", str(int(max_frames))),
        ("INCLUDE_DISP", "1" if include_disp else "0"),
    ]
    head = ["# extract_settings.tcl - generated by PhysicsAI platform (geometry-view.md 13.3). Do not edit.",
            "# Values are Tcl double-quoted literals; non-ASCII characters are \\uXXXX escapes."]
    return "\n".join(head + [f"set {k:<12} {v}" for k, v in rows]) + "\n"


def parse_result(text: str) -> dict[str, Any]:
    """extract_result.txt → {status, message, unit, field, dcomp, avgmode, nodes, faces, frames_total, frames:[(out, src, time)]}."""
    out: dict[str, Any] = {"status": None, "message": None, "unit": "", "field": "", "dcomp": "", "avgmode": "", "nodes": None,
                           "faces": None, "frames_total": None, "frames": [], "header_ok": False}
    for raw in text.splitlines():
        line = raw.strip().lstrip("﻿")
        if line.startswith("# contour_extract"):
            out["header_ok"] = True
            continue
        if not line or line.startswith("#"):
            continue
        key, sep, val = line.partition("=")
        if not sep:
            continue
        val = val.strip()
        if key == "STATUS":
            out["status"] = val or None
        elif key == "MESSAGE":
            out["message"] = val[:300] or None
        elif key in ("UNIT", "FIELD", "DCOMP", "AVGMODE"):
            out[key.lower()] = val[:120]
        elif key in ("NODES", "FACES", "FRAMES_TOTAL"):
            out[key.lower()] = int(val) if val.isdigit() else None
        elif key == "FRAME":
            parts = val.split("|")
            if len(parts) >= 2 and parts[0].strip().isdigit() and parts[1].strip().isdigit():
                out["frames"].append((int(parts[0]), int(parts[1]), _time(parts[2] if len(parts) > 2 else "")))
    return out


def _time(s: str) -> float | None:
    """h3d 시뮬레이션 시간(라벨 `Time = 0.0012` 형식이면 숫자만)."""
    import re

    m = re.search(r"[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?", s or "")
    return float(m.group(0)) if m else None


def cache_key(*, source_kind: str, source_id: str, h3d_size: int, h3d_mtime_ns: int, display: Mapping[str, Any], max_frames: int,
              include_disp: bool) -> str:
    """§13.5: sha256(정규 JSON) — h3d 내용 해시는 대형이라 계산하지 않음(크기·mtime)."""
    doc = {"source_kind": source_kind, "source_id": source_id, "h3d_size": int(h3d_size), "h3d_mtime_ns": int(h3d_mtime_ns),
           "display": {"field": str(display.get("field") or ""), "dcomp": str(display.get("component") or display.get("comp") or ""),
                       "avgmode": str(display.get("avgmode") or "")},
           "max_frames": int(max_frames), "include_disp": bool(include_disp), "converter_version": CONVERTER_VERSION}
    return hashlib.sha256(json.dumps(doc, sort_keys=True, separators=(",", ":")).encode("utf-8")).hexdigest()
