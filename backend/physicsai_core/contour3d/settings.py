def settings_text(*, h3d_path: str, out_dir: str, display: Mapping[str, Any], max_frames: int, include_disp: bool,
                  disp_max_nodes: int = 0) -> str:
    """extract_settings.tcl(ASCII, `/` 경로 — capture_settings.tcl과 같은 이스케이프 규칙). 기존 키 뒤에 COMPS·DISP_MAX_NODES(§9.1).
    COMPS = display["comps"](쿠션 입력 예측은 API가 `[]`로 비워 보낸다, §9.5). 단위(display.unit)는 TCL에 넘기지 않는다(C3F-14)."""
    rows = [
        ("H3D_PATH", tcl_quote(h3d_path.replace("\\", "/"))),
        ("OUTDIR", tcl_quote(out_dir.replace("\\", "/"))),
        ("FIELD", tcl_quote(str(display.get("field") or ""))),
        ("DCOMP", tcl_quote(str(display.get("component") or display.get("comp") or ""))),
        ("AVGMODE", tcl_quote(str(display.get("avgmode") or ""))),
        ("MAX_FRAMES", str(int(max_frames))),
        ("INCLUDE_DISP", "1" if include_disp else "0"),
        ("COMPS", tcl_list(normalize_comps(display.get("comps")))),
        ("DISP_MAX_NODES", str(max(0, int(disp_max_nodes)))),
    ]
    head = ["# extract_settings.tcl - generated by PhysicsAI platform (geometry-view.md 13.3, contour3d-field.md 9.1). Do not edit.",
            "# Values are Tcl double-quoted literals; non-ASCII characters are \\uXXXX escapes."]
    return "\n".join(head + [f"set {k:<12} {v}" for k, v in rows]) + "\n"


def normalize_comps(comps: Iterable[Any] | None) -> list[str]:
    """부품 이름 목록 → 공백 제거·중복 제거·정렬(캐시 키·COMPS 모두 같은 규칙, 순서·중복은 키에 영향 없음)."""
    return sorted({str(c).strip() for c in (comps or []) if str(c).strip()})


_UNIT_BAD = re.compile(r'[\s":]|invalid|error', re.IGNORECASE)


def clean_unit(raw: Any) -> str:
    """단위 값 정화(§9.2): 16자 초과·공백·`"`·`:`·`invalid`·`error`(대소문자 무시)가 들어 있으면 오류 문구로 보고 `""`."""
    u = str(raw if raw is not None else "").strip()
    return "" if not u or len(u) > 16 or _UNIT_BAD.search(u) else u


def parse_result(text: str) -> dict[str, Any]:
    """extract_result.txt → {status, message, unit(정화됨), field, dcomp, avgmode, nodes, faces, frames_total, frames:[(out, src, time)],
    disp, disp_reason, disp_missing_frames, scope}."""
    out: dict[str, Any] = {"status": None, "message": None, "unit": "", "field": "", "dcomp": "", "avgmode": "", "nodes": None,
                           "faces": None, "frames_total": None, "frames": [], "header_ok": False,
                           # §9.4: 예전 TCL(키 없음)이면 disp=None·scope=None
                           "disp": None, "disp_reason": "", "disp_missing_frames": 0, "scope": None}
    for raw in text.splitlines():
        line = raw.strip().lstrip("﻿")
        if line.startswith("# contour_extract"):
            out["header_ok"] = True
            continue
        if not line or line.startswith("#"):
            continue
        key, sep, val = line.partition("=")
        if not sep:
            continue
        val = val.strip()
        if key == "STATUS":
            out["status"] = val or None
        elif key == "MESSAGE":
            out["message"] = val[:300] or None
        elif key == "UNIT":
            out["unit"] = clean_unit(val)
        elif key in ("FIELD", "DCOMP", "AVGMODE"):
            out[key.lower()] = val[:120]
        elif key == "DISP":
            out["disp"] = val.upper() if val.upper() in DISP_STATES else None
        elif key == "DISP_REASON":
            out["disp_reason"] = val[:120]
        elif key == "DISP_MISSING_FRAMES":
            out["disp_missing_frames"] = int(val) if val.isdigit() else 0
        elif key == "SCOPE":
            out["scope"] = val.upper() if val.upper() in SCOPES else None
        elif key in ("NODES", "FACES", "FRAMES_TOTAL"):
            out[key.lower()] = int(val) if val.isdigit() else None
        elif key == "FRAME":
            parts = val.split("|")
            if len(parts) >= 2 and parts[0].strip().isdigit() and parts[1].strip().isdigit():
                out["frames"].append((int(parts[0]), int(parts[1]), _time(parts[2] if len(parts) > 2 else "")))
    return out


def _time(s: str) -> float | None:
    """h3d 시뮬레이션 시간(라벨 `Time = 0.0012` 형식이면 숫자만)."""
    import re

    m = re.search(r"[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?", s or "")
    return float(m.group(0)) if m else None


def limits_of(c: Any) -> dict[str, int]:
    """캐시 키·변환기에 넘기는 상한(설정 `contour3d.*`, §10)."""
    return {"max_nodes": int(c.max_nodes), "max_glb_bytes": int(c.max_glb_bytes), "max_bin_bytes": int(c.max_bin_bytes),
            "max_disp_bytes": int(c.max_disp_bytes), "disp_max_nodes": int(c.disp_max_nodes)}


_TCL_HASH_MEMO: dict[str, tuple[int, int, str]] = {}


def tcl_hash(path: str | None) -> str:
    """유효 추출 TCL 내용의 sha256 앞 16자(§10) — (크기, mtime_ns) 메모 캐시. 파일이 없으면 `""`."""
    if not path:
        return ""
    try:
        st = os.stat(path)
    except OSError:
        return ""
    hit = _TCL_HASH_MEMO.get(path)
    if hit and hit[0] == st.st_size and hit[1] == st.st_mtime_ns:
        return hit[2]
    with open(path, "rb") as fh:
        h = hashlib.sha256(fh.read()).hexdigest()[:16]
    _TCL_HASH_MEMO[path] = (st.st_size, st.st_mtime_ns, h)
    return h


def cache_key(*, source_kind: str, source_id: str, h3d_size: int, h3d_mtime_ns: int, display: Mapping[str, Any], max_frames: int,
              include_disp: bool, comps: Iterable[Any] | None = None, limits: Mapping[str, int] | None = None,
              lod_min_nodes: int = 0, lod_target_vertices: int = 0, meshopt: bool = True, extract_tcl: str = "") -> str:
    """§10: sha256(정규 JSON) — h3d 내용 해시는 대형이라 계산하지 않음(크기·mtime). 상한·부품 이름·단위·LOD·meshopt·추출 TCL 해시·
    converter_version이 키에 들어가서 설정·TCL을 바꾸면 캐시된 FAIL이 새로 계산된다(C3F-11). comps는 정렬·중복 제거."""
    lim = dict(limits or {})
    doc = {"source_kind": source_kind, "source_id": source_id, "h3d_size": int(h3d_size), "h3d_mtime_ns": int(h3d_mtime_ns),
           "display": {"field": str(display.get("field") or ""), "dcomp": str(display.get("component") or display.get("comp") or ""),
                       "avgmode": str(display.get("avgmode") or ""), "unit": clean_unit(display.get("unit"))},
           "comps": normalize_comps(comps if comps is not None else display.get("comps")),
           "max_frames": int(max_frames), "include_disp": bool(include_disp),
           "limits": {k: int(lim[k]) for k in sorted(lim)},
           "lod": {"min_nodes": int(lod_min_nodes), "target_vertices": int(lod_target_vertices)}, "meshopt": bool(meshopt),
           "extract_tcl": str(extract_tcl), "converter_version": CONVERTER_VERSION}
    return hashlib.sha256(json.dumps(doc, sort_keys=True, separators=(",", ":")).encode("utf-8")).hexdigest()
