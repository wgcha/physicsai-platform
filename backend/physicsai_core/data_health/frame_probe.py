"""프레임 조회 `DH_FRAMES` 설정·결과 파일(data-health.md §3.6 ③, DH-18) — `resources/hyperview/h3d_frame_probe.tcl`의 짝.

설정 `frame_probe_settings.tcl`(ASCII, `/` 경로, Tcl 큰따옴표 리터럴 — capture_settings.tcl과 같은 이스케이프)에 대상 `{idx, h3d, out}` 목록을 쓰고,
TCL이 파일마다 `frames/<idx>.txt`(`extract_result.txt` 형식)를 쓰면 기존 `contour3d.settings.parse_result` 파서로 읽는다.
"""

from __future__ import annotations

import os
from collections.abc import Sequence
from dataclasses import dataclass
from typing import Any

from ..contour3d.settings import parse_result
from ..stage4_predict.contour_capture import tcl_quote

SCRIPT_NAME = "h3d_frame_probe.tcl"
SETTINGS_NAME = "frame_probe_settings.tcl"
FRAMES_DIR = "frames"


def settings_text(targets: Sequence[dict[str, Any]]) -> str:
    """targets = [{idx, h3d, out}] → frame_probe_settings.tcl 본문."""
    rows = [f"    [list {int(t['idx'])} {tcl_quote(str(t['h3d']).replace(chr(92), '/'))} {tcl_quote(str(t['out']).replace(chr(92), '/'))}]"
            for t in targets]
    head = ["# frame_probe_settings.tcl - generated by PhysicsAI platform (data-health.md DH-18). Do not edit.",
            "# Values are Tcl double-quoted literals; non-ASCII characters are \\uXXXX escapes."]
    return "\n".join(head + ["set PROBE_TARGETS [list \\", *[r + " \\" for r in rows], "]"]) + "\n"


@dataclass(frozen=True)
class ProbeResult:
    ok: bool
    frames: int | None = None
    t_last: float | None = None
    code: str | None = None      # 실패 사유(FRAMES_PROBE_FAILED)
    message: str | None = None


def read_result(path: str, max_bytes: int = 4 * 1024 * 1024) -> ProbeResult:
    """`frames/<idx>.txt` 1개 → 결과. 없음·너무 큼·STATUS≠OK·프레임 수 없음 = 실패(FRAMES_PROBE_FAILED). 시각은 마지막 프레임 라벨의 숫자."""
    try:
        if os.path.getsize(path) > max_bytes:
            return ProbeResult(False, code="FRAMES_PROBE_FAILED", message="결과 파일이 너무 큼")
        with open(path, encoding="utf-8", errors="replace") as fh:
            res = parse_result(fh.read())
    except OSError:
        return ProbeResult(False, code="FRAMES_PROBE_FAILED", message="결과 파일 없음")
    if res["status"] != "OK" or not res["frames_total"]:
        return ProbeResult(False, code="FRAMES_PROBE_FAILED", message=f"{res['status'] or 'STATUS 없음'} {res['message'] or ''}".strip())
    frames = res["frames"]
    t = frames[-1][2] if frames else None
    return ProbeResult(True, int(res["frames_total"]), t)
