"""④ 예측 응답 추출 — 원본 ⑤ m_4 방식(phase3 §14.6, D3-49): `H3D_REQUESTS.txt` 작성 · `RESPONSES.txt` 파싱 · stat 적용.

원본 `H3D_StaticMinMax_to_CSV_FAST.tcl`(tbcload, 리터럴 해독): 스크립트 **자기 폴더**의 `H3D_REQUESTS.txt`(UTF-8, `#` 줄 무시,
필드 `|` 구분)를 읽고, 같은 폴더의 `*_pred.h3d`(없으면 `*.h3d`)를 열어 요청마다 전 프레임 최소·최대를 `RESPONSES.txt`에 쓴다:
머리 `# RESPONSES.txt generated …`, 값 줄 `RESP:<NAME>_MIN=%20.10e`·`RESP:<NAME>_MAX=…`, 실패 줄 `RESP:<NAME>=NO_VALUE|OPEN_ERROR|
DATATYPE_ERR|HANDLE_ERR`, 로그 `RESPONSES.log`.

요청 줄 필드 순서(`REQUEST_FIELDS`)는 로그 문구로 본 **추정값**(서버 확인 E4-9-5 전) — 바뀌면 이 상수 하나만 고친다(변경 메모).
워커(④ RESPONSE_EXTRACT·PV_EXTRACT·①-6 RESPONSE_EXTRACT_RUNS) 공용. 순수 함수(파일 I/O는 `write_requests`·`read_responses`만).
"""

from __future__ import annotations

import fnmatch
import math
import os
import re
from collections.abc import Mapping, Sequence
from dataclasses import dataclass, field
from typing import Any

REQUESTS_FILE = "H3D_REQUESTS.txt"
RESPONSES_FILE = "RESPONSES.txt"
RESPONSES_LOG = "RESPONSES.log"
# E4-9-5 확인 전 추정(원본 TCL 로그 "Request '<NAME>' : subcase= type= comp= layer="). 바뀌면 여기만.
REQUEST_FIELDS: tuple[str, ...] = ("NAME", "SUBCASE", "DATATYPE", "COMPONENT", "LAYER")
REQUEST_SEP = "|"
FAIL_TOKENS = ("NO_VALUE", "OPEN_ERROR", "DATATYPE_ERR", "HANDLE_ERR")
STATS = ("MAX", "MIN", "ABSMAX")
PRED_H3D_GLOB = "*_pred.h3d"  # TCL이 먼저 찾는 이름(없으면 *.h3d)

_RESP_RE = re.compile(r"^\s*RESP:(?P<key>[^=\s]+)\s*=\s*(?P<val>\S+)\s*$")
_FORBIDDEN = re.compile(r"[|\r\n\t]")

# 응답 표 사유(화면 문구). 키 = 실패 토큰 또는 플랫폼 사유
REASON_TEXT = {
    "NO_VALUE": "값 없음(NO_VALUE)",
    "OPEN_ERROR": "h3d 열기 실패(OPEN_ERROR)",
    "DATATYPE_ERR": "결과 종류 없음(DATATYPE_ERR)",
    "HANDLE_ERR": "HyperView 처리 실패(HANDLE_ERR)",
    "NOT_H3D": "추출 정의(H3D) 없음",
    "SPEC_INVALID": "추출 정의가 올바르지 않음",
    "MISSING": "RESPONSES.txt에 값 없음",
    "EXTRACT_FAILED": "추출 실패",
}


@dataclass(frozen=True)
class H3dRequest:
    """요청 1줄(응답 1개)."""

    name: str
    subcase: int
    datatype: str
    component: str
    layer: str
    stat: str

    def fields(self) -> dict[str, str]:
        return {"NAME": self.name, "SUBCASE": str(self.subcase), "DATATYPE": self.datatype,
                "COMPONENT": self.component, "LAYER": self.layer}

    def line(self) -> str:
        f = self.fields()
        return REQUEST_SEP.join(f[k] for k in REQUEST_FIELDS)


@dataclass
class ParsedResponses:
    """RESPONSES.txt 파싱 결과: 값(`<NAME>_MIN`/`_MAX` → float), 실패(`<NAME>` → 토큰)."""

    values: dict[str, float] = field(default_factory=dict)
    failures: dict[str, str] = field(default_factory=dict)


def _get(spec: Mapping[str, Any], key: str) -> Any:
    """spec 키는 소문자(플랫폼) 또는 대문자(원본 ⑤ RESPONSES 형식) 모두 받는다."""
    if key in spec:
        return spec[key]
    return spec.get(key.upper())


def h3d_request(resp: Mapping[str, Any]) -> tuple[H3dRequest | None, str | None]:
    """응답 정의 `{name, unit, spec:{source:"H3D", subcase, datatype, component, layer, stat}}` → (요청, None) 또는 (None, 사유)."""
    name = str(resp.get("name") or "")
    spec = resp.get("spec")
    if not isinstance(spec, Mapping) or str(_get(spec, "source") or "H3D").upper() != "H3D":
        return None, "NOT_H3D"
    if not _get(spec, "datatype") or not _get(spec, "component"):
        return None, "NOT_H3D"
    try:
        sc = _get(spec, "subcase")
        subcase = int(sc) if sc is not None and not isinstance(sc, bool) and float(sc) == int(sc) else 0
    except (TypeError, ValueError):
        subcase = 0
    stat = str(_get(spec, "stat") or "MAX").upper()
    datatype, component, layer = (str(_get(spec, k) or "").strip() for k in ("datatype", "component", "layer"))
    if (not name or subcase < 1 or stat not in STATS or not datatype or not component
            or any(_FORBIDDEN.search(x) for x in (name, datatype, component, layer))):
        return None, "SPEC_INVALID"
    return H3dRequest(name, subcase, datatype, component, layer, stat), None


def build_requests(responses: Sequence[Mapping[str, Any]]) -> tuple[list[H3dRequest], dict[str, str]]:
    """응답 정의 목록 → (요청 목록, 요청 못 한 응답 {name: 사유})."""
    reqs: list[H3dRequest] = []
    skipped: dict[str, str] = {}
    for r in responses:
        req, why = h3d_request(r)
        if req is None:
            skipped[str(r.get("name") or "")] = why or "SPEC_INVALID"
        else:
            reqs.append(req)
    return reqs, skipped


def requests_text(requests: Sequence[H3dRequest]) -> str:
    """`H3D_REQUESTS.txt` 본문: `#` 머리 2줄(설명·필드 순서) + 요청마다 1줄. UTF-8, 끝 줄바꿈."""
    lines = ["# H3D_REQUESTS.txt generated by PhysicsAI platform (phase3 §14.6)",
             "# " + REQUEST_SEP.join(REQUEST_FIELDS)]
    lines += [r.line() for r in requests]
    return "\n".join(lines) + "\n"


def write_requests(folder: str, requests: Sequence[H3dRequest]) -> str:
    """folder/H3D_REQUESTS.txt 작성(UTF-8, LF, SPDM 보호 확인). 경로를 돌려준다."""
    from ..fileutil import write_text

    path = os.path.join(folder, REQUESTS_FILE)
    write_text(path, requests_text(requests))
    return path


def parse_responses_text(text: str) -> ParsedResponses:
    """`RESPONSES.txt` 본문 파싱. `#` 줄·모르는 줄 무시. 값이 수가 아니거나 유한하지 않으면 그 키는 실패 토큰으로."""
    out = ParsedResponses()
    for raw in text.lstrip("﻿").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        m = _RESP_RE.match(line)
        if not m:
            continue
        key, val = m.group("key"), m.group("val")
        if val.upper() in FAIL_TOKENS:
            out.failures[key] = val.upper()
            continue
        try:
            f = float(val)
        except ValueError:
            out.failures[key] = "NO_VALUE"
            continue
        if math.isfinite(f):
            out.values[key] = f
        else:
            out.failures[key] = "NO_VALUE"
    return out


def read_responses(folder: str) -> ParsedResponses | None:
    """folder/RESPONSES.txt(없으면 None)."""
    path = os.path.join(folder, RESPONSES_FILE)
    if not os.path.isfile(path):
        return None
    with open(path, encoding="utf-8", errors="replace") as fh:
        return parse_responses_text(fh.read())


def apply_stat(req: H3dRequest, parsed: ParsedResponses) -> tuple[float | None, str | None]:
    """stat 적용: MAX = `_MAX`, MIN = `_MIN`, ABSMAX = max(|min|,|max|). 값 없으면 (None, 사유 토큰)."""
    lo = parsed.values.get(f"{req.name}_MIN")
    hi = parsed.values.get(f"{req.name}_MAX")
    fail = parsed.failures.get(req.name) or parsed.failures.get(f"{req.name}_{'MIN' if req.stat == 'MIN' else 'MAX'}")
    if req.stat == "MAX":
        v = hi
    elif req.stat == "MIN":
        v = lo
    else:
        v = max(abs(lo), abs(hi)) if lo is not None and hi is not None else None
    if v is None:
        return None, fail or "MISSING"
    return v, None


def pick_values(responses: Sequence[Mapping[str, Any]], parsed: ParsedResponses | None,
                *, skipped: Mapping[str, str] | None = None, failed_reason: str = "EXTRACT_FAILED"
                ) -> tuple[dict[str, float | None], dict[str, str]]:
    """응답 정의 순서대로 {name: 값|None}과 {name: 사유}(값 없는 응답만). parsed None = 추출 자체 실패(전부 failed_reason)."""
    values: dict[str, float | None] = {}
    reasons: dict[str, str] = {}
    for r in responses:
        name = str(r.get("name") or "")
        if skipped and name in skipped:
            values[name], reasons[name] = None, skipped[name]
            continue
        req, why = h3d_request(r)
        if req is None:
            values[name], reasons[name] = None, why or "SPEC_INVALID"
            continue
        if parsed is None:
            values[name], reasons[name] = None, failed_reason
            continue
        v, reason = apply_stat(req, parsed)
        values[name] = v
        if reason:
            reasons[name] = reason
    return values, reasons


def reason_text(code: str) -> str:
    return REASON_TEXT.get(code, code)


def name_value_csv_text(values: Mapping[str, float | None]) -> str:
    """`name,value` CSV(값 없음 = 빈 칸) — RESPONSE_TABLE·PV_TABLE·①-6 표가 그대로 읽는다(parsers.name_value)."""
    lines = ["name,value"]
    for k, v in values.items():
        lines.append(f"{k},{'' if v is None else repr(float(v))}")
    return "\n".join(lines) + "\n"


def h3d_candidates(folder: str) -> list[str]:
    """TCL이 읽을 h3d(원본: `*_pred.h3d`, 없으면 `*.h3d`) — 직계 파일 이름 목록(정렬)."""
    try:
        names = sorted(n for n in os.listdir(folder) if os.path.isfile(os.path.join(folder, n)))
    except OSError:
        return []
    pred = [n for n in names if fnmatch.fnmatch(n.lower(), PRED_H3D_GLOB)]
    return pred or [n for n in names if n.lower().endswith(".h3d")]
