# ---- curve_stats ---------------------------------------------------------------------------------


def test_curve_stats_golden_and_exclusions():
    c = _curve([
        {"name": "Node 100 / X", "x": [0, 0.001, 0.002, 0.003], "y": [0.0, 152.3, -3.1, 152.3]},
        {"name": "Node 200 / Z", "x": [0, 1, 2], "y": [-9.5, -1.0, 4.0]},
        {"name": "nan", "x": [0, 1], "y": [1.0, float("nan")]},
        {"name": "inf", "x": [0, 1], "y": [1.0, float("inf")]},
        {"name": "len", "x": [0, 1, 2], "y": [1.0, 2.0]},
        {"name": "empty", "x": [], "y": []},
        {"name": "bool", "x": [0, 1], "y": [True, 2.0]},
        {"name": "Node 100 / X", "x": [0], "y": [999.0]},       # 같은 이름 → 첫 계열만
        {"name": "", "x": [0], "y": [1.0]},
        "not-a-dict",
    ])
    s = curve_stats(c)
    assert list(s) == ["Node 100 / X", "Node 200 / Z"]
    assert s["Node 100 / X"] == {"max": 152.3, "min": -3.1, "absmax": 152.3, "x_at_max": 0.001, "x_at_min": 0.002, "n": 4.0}
    assert s["Node 200 / Z"] == {"max": 4.0, "min": -9.5, "absmax": 9.5, "x_at_max": 2.0, "x_at_min": 0.0, "n": 3.0}
    assert curve_stats({}) == {} and curve_stats({"series": "x"}) == {}


def test_curve_stats_series_cap():
    c = _curve([{"name": f"S{i}", "x": [0, 1], "y": [i, -i]} for i in range(60)])
    s = curve_stats(c)
    assert len(s) == rm.MAX_SERIES == 50 and list(s)[-1] == "S49"


