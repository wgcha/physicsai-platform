def _study(tmp_path: Path) -> Path:
    root = tmp_path / "AI" / "S1"
    _write(root / "04_batch" / "B-001" / "run__00001" / "P" / "curve.json", json.dumps(_curve([{"name": "N", "x": [0], "y": [1]}])))
    _write(root / "04_batch" / "B-001" / "run__00001" / "P" / "RESULT" / "RESPONSES.txt", RESP_TEXT)
    return root


def test_locate_run_files_ok_and_missing(tmp_path):
    root = _study(tmp_path)
    arts = {"a1": {"rel_path": "04_batch/B-001/run__00001/P/curve.json"}}
    job = {"result": {"curve_artifact_id": "a1", "pred_h3d_rel": "04_batch\\B-001\\run__00001\\P\\RESULT\\x_pred.h3d"}}
    f = rm.locate_run_files(None, str(root), job, get_artifact=lambda _c, i: arts.get(i))
    assert f.curve_json == str(root / "04_batch" / "B-001" / "run__00001" / "P" / "curve.json")
    assert f.result_dir == str(root / "04_batch" / "B-001" / "run__00001" / "P" / "RESULT")
    m = rm.load_run_metrics(f, max_bytes=10 ** 6)
    assert m.curve and m.resp == {"CornerStress_MIN": 0.0, "CornerStress_MAX": 151.9}
    # 결과 키 없음·artifact 없음·파일 없음 → None
    for j in (None, {}, {"result": None}, {"result": {"curve_artifact_id": "zz"}},
              {"result": {"curve_artifact_id": "a1", "pred_h3d_rel": "nope/RESULT/x.h3d"}}):
        g = rm.locate_run_files(None, str(root), j, get_artifact=lambda _c, i: {"a1": {"rel_path": "gone.json"}}.get(i))
        assert g.curve_json is None and g.result_dir is None
    assert rm.locate_run_files(None, str(root), {"result": {"pred_h3d_rel": "x.h3d"}}).result_dir is None  # 부모 = Study 자체


def test_path_safety_rejects_outside_and_links(tmp_path):
    root = _study(tmp_path)
    outside = _write(tmp_path / "AI" / "secret" / "curve.json", json.dumps(_curve([{"name": "N", "x": [0], "y": [1]}])))
    _write(tmp_path / "AI" / "secret" / "RESULT" / "RESPONSES.txt", RESP_TEXT)
    for rel in ("../secret/curve.json", "/etc/passwd", "C:/Windows/win.ini", "04_batch/../../secret/curve.json", "", ".", None):
        assert rm.safe_study_path(str(root), rel) is None, rel
    assert rm.safe_study_path(str(root), "04_batch/B-001") == str(root / "04_batch" / "B-001")
    # 파일 링크(밖·안 모두) 거부
    (root / "link.json").symlink_to(outside)
    (root / "inner_link.json").symlink_to(root / "04_batch" / "B-001" / "run__00001" / "P" / "curve.json")
    assert rm.safe_study_path(str(root), "link.json") is None
    assert rm.safe_study_path(str(root), "inner_link.json") is None
    # 중간 폴더 링크 거부
    (root / "linkdir").symlink_to(tmp_path / "AI" / "secret", target_is_directory=True)
    assert rm.safe_study_path(str(root), "linkdir/curve.json") is None
    job = {"result": {"curve_artifact_id": "a", "pred_h3d_rel": "linkdir/RESULT/x_pred.h3d"}}
    f = rm.locate_run_files(None, str(root), job, get_artifact=lambda _c, _i: {"rel_path": "link.json"})
    assert f == RunFiles(None, None)
    # RESPONSES.txt 자체가 링크면 읽지 않는다
    res = root / "04_batch" / "B-001" / "run__00002" / "P" / "RESULT"
    res.mkdir(parents=True)
    (res / "RESPONSES.txt").symlink_to(tmp_path / "AI" / "secret" / "RESULT" / "RESPONSES.txt")
    assert rm.load_run_metrics(RunFiles(None, str(res)), max_bytes=10 ** 6).resp is None


