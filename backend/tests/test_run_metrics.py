def test_lru_reads_once_and_rereads_on_change(tmp_path, monkeypatch):
    cj = _write(tmp_path / "curve.json", json.dumps(_curve([{"name": "N", "x": [0, 1], "y": [1, 2]}])))
    res = tmp_path / "RESULT"
    _write(res / "RESPONSES.txt", RESP_TEXT)
    calls = {"curve": 0, "resp": 0}
    orig_c, orig_r = rm._load_curve, rm._load_resp
    monkeypatch.setattr(rm, "_load_curve", lambda p: (calls.__setitem__("curve", calls["curve"] + 1), orig_c(p))[1])
    monkeypatch.setattr(rm, "_load_resp", lambda p: (calls.__setitem__("resp", calls["resp"] + 1), orig_r(p))[1])
    files = RunFiles(str(cj), str(res))
    a = rm.load_run_metrics(files, max_bytes=10 ** 6)
    b = rm.load_run_metrics(files, max_bytes=10 ** 6)
    assert calls == {"curve": 1, "resp": 1} and a == b
    assert rm.cache_info()["hits"] == 2 and rm.cache_info()["size"] == 2
    # 내용·mtime 바뀜 → 다시 읽음
    cj.write_text(json.dumps(_curve([{"name": "N", "x": [0, 1], "y": [1, 99]}])), encoding="utf-8")
    st = cj.stat()
    os.utime(cj, ns=(st.st_atime_ns, st.st_mtime_ns + 5_000_000_000))
    c = rm.load_run_metrics(files, max_bytes=10 ** 6)
    assert calls == {"curve": 2, "resp": 1} and c.curve["N"]["max"] == 99.0
    # mtime만 바뀌어도(크기 같음) 다시 읽음
    st = (res / "RESPONSES.txt").stat()
    os.utime(res / "RESPONSES.txt", ns=(st.st_atime_ns, st.st_mtime_ns + 7_000_000_000))
    rm.load_run_metrics(files, max_bytes=10 ** 6)
    assert calls["resp"] == 2


def test_lru_eviction():
    lru = rm._Lru(2)
    loads = []
    for k in ("a", "b", "a", "c", "b"):
        lru.get_or_load((k,), lambda k=k: loads.append(k) or k)
